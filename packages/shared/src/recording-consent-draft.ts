/**
 * 동의서 "설명 요지"·시드 견본 본문 — 상태 표시가 **본문 첫 줄에** 박힌다(라벨만 따로 두면 인쇄에서 떨어진다).
 */
export function recordingConsentDraftText(): string {
  const d = RECORDING_CONSENT_DRAFT;
  const head = `※ ${d.statusLabel}(${d.draftedOn} · ${d.section}) — 확정 문안이 아닙니다. [ ] 안은 기관이 확정하기 전까지 비어 있습니다.`;
  const body = d.items.map((it) => `${it.no}. ${it.heading}: ${it.text}`).join('\n');
  return [head, '', d.title, '', d.intro, '', body].join('\n');
}

