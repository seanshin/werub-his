import { describe, it, expect } from 'vitest';
import { AREA_CATALOGS } from '../src/i18n/messages/registry';

/**
 * 🔴 교차 카탈로그 번역 충돌 가드 (2026-09-07 P2 합류 검토에서 실측된 구조 결함).
 *
 * 병렬 8기가 각자 영역 카탈로그를 채웠고, `t()` 는 **먼저 등록된 카탈로그가 이긴다**
 * (registry.ts 등록 순서). 같은 한국어 원문에 서로 다른 번역이 등재되면
 * **사용자가 보는 값이 등록 순서로 정해진다** — 화면 문맥과 무관하게.
 *
 * 실측 71건(의미차이 50·표기차이 21). 예: '서명'(버튼)이 status 의 'Signed'(상태)로,
 * '불출'(버튼)이 'Issued'(완료 상태)로 덮여 **버튼에 과거분사가 뜬다**.
 *
 * 해법은 문맥 키(`원문@문맥`)다. 이 가드는 **조용히 늘지 않게 수를 못박는다** —
 * 줄이면 기준선을 낮추고, 늘면 실패한다(여유를 두면 신규 위반을 흡수한다).
 */

/**
 * 🔴 **정본에서 파생한다 — 베껴 적지 않는다.**
 *    종전엔 여기 11종을 수기로 나열했고, P2b 가 8종을 추가하자 **가드가 그 8종을 아예 보지
 *    않았다**(2026-09-07 재주입에서 발각: 새 의미 충돌을 넣었는데 가드가 통과했다).
 *    수기 목록이 낡는 것은 계약 드리프트 축의 알려진 기전이다 — 등록 순서 정본을 그대로 쓴다.
 */
const ORDER: [string, Record<string, Record<string, string> | undefined>][] =
  AREA_CATALOGS.map((a) => [a.area, a.c as Record<string, Record<string, string> | undefined>]);

/** 대소문자·공백·하이픈·복수형 차이는 표기 차이로 본다(오역이 아니다) */
const norm = (s: string) => s.toLowerCase().replace(/[\s\-&/]+/g, '').replace(/s$/, '');

function collect() {
  const seen = new Map<string, { area: string; en: string }[]>();
  for (const [area, cat] of ORDER) {
    for (const [k, en] of Object.entries(cat.en ?? {})) {
      if (!seen.has(k)) seen.set(k, []);
      seen.get(k)!.push({ area, en });
    }
  }
  const dup = [...seen.entries()].filter(([, v]) => v.length > 1);
  const conflict = dup.filter(([, v]) => new Set(v.map((x) => x.en)).size > 1);
  const semantic = conflict.filter(([, v]) => new Set(v.map((x) => norm(x.en))).size > 1);
  return { dup, conflict, semantic };
}

describe('🔴 교차 카탈로그 번역 충돌 — 등록 순서가 사용자에게 보이는 값을 정한다', () => {
  it('의미가 갈리는 충돌이 기준선을 넘지 않는다(문맥 키로 줄여 나간다)', () => {
    const { semantic } = collect();
    // 2026-09-07 실측: 50 → 품사 오역 8건 회수(문맥 키 분리 4·중복 제거 3·rename 1) → **43**
    // 2026-09-07 P2b 합류(영역 카탈로그 8종 추가·가드 시야 11→19): 위험 5건 회수 후 **50**
    //   회수분은 전부 **뜻이 달라지는** 자리였다(표기 차이가 아니라):
    //     · 횟수 = 용법 빈도인데 'Visits'(방문 횟수)로 나갔다 → `횟수@용법`(정본은 이미 있었고 약국 화면이 안 쓰고 있었다)
    //     · 퇴실 = ICU·회복실 퇴실인데 'Left ER'로 나갔다 → `퇴실@병동`
    //     · 산출 불가 = 분모 0·표본 부재로 계산 불가인데 'Unavailable'로 흐려졌다 → 'Not computable' 로 정본 일치
    //     · 접수 = 상태 배지인데 'Reception'(부서명)으로 나갔다 → `접수@상태`(정본 존재·미배선)
    //     · 이름 = 직원 성명인데 'Given name'(名)으로 나갔다 → 소비처 0인 정의를 'Name' 으로 일치
    // 2026-09-07 **전수 판정 라운드**: 남은 50건을 "동의어일 것"으로 두지 않고 **50건 전부
    //   사용처를 눌러 확인**했다(정적 `<T k="…">`·동적 `<T k={라벨상수}>`·`tAttr`·StatusBadge 4경로).
    //   결과 **A 오역 23 · B 무해 26 · C 사용처 없음 1 · D 0** → 의미 충돌 **50 → 0**.
    //   🔴 "동의어로 보이는데 실은 다른 뜻"이 23건이었다 — 카탈로그만 보고 판정했다면 전부 놓쳤다:
    //     · 비급여 = 보험 적용 여부인데 'Self-pay'(자비)로 나갔다(같은 패널 합계는 'Non-covered total')
    //     · 원내 = 원내 처방집 등재인데 'On-site'(지금 병원에 있는 환자)로 → 약품·수가 표 4곳
    //     · 판정 = 검사 결과 등급인데 'Assessment'(간호 사정)로 → **이긴 정의 자체가 틀려** 값을 정정
    //     · 완료 = 상태 'Completed' 가 **동작 버튼 8곳**을 덮었다 → `완료@버튼`
    //     · 접수 = 오더 스텝퍼 'Received' 자리에 'Reception'(창구) → `접수@상태`
    //     · 기본 = 검진 등급 BASIC 인데 'Default'(기본값) · 미등록 = 식단 미등록인데 'Not enrolled'(생체등록)
    //   B/C 28건은 **지는 쪽 죽은 정의를 제거**했다(이긴 쪽은 하나도 건드리지 않았다).
    // 🔴 여유를 두지 않는다: 한때 55로 두었더니 재주입한 신규 충돌 1건을 **그대로 흡수했다**
    //    (주입 성공 0→1 을 확인했는데도 가드가 통과했다 · 2026-09-07). 실측값에 정확히 못박는다.
    // 🔴 **그런데 이 기준선은 0 이 아니다** — 같은 날 `patients2` 가 등재되면서 **새 충돌 18건**이
    //    들어왔다(전부 patients2 가 지는 쪽 = 죽은 정의). 그 18건은 **판정하지 않았다** —
    //    사용처를 누르지 않고 "동의어처럼 보인다"로 넘기는 것이 바로 이 라운드가 없앤 습관이다.
    //    그래서 **내가 판정한 몫(0)과 남의 미판정 몫(18)을 섞어 한 숫자로 말하지 않는다**:
    //      · 내가 전수 판정한 19개 영역 사이 의미 충돌 = **0** — 재발 방지는 아래 두 번째 it 의
    //        키 목록 30종이 **여유 0**으로 못박는다(표기 차이도 실패한다).
    //      · 아래 BASELINE = 미판정 신규분을 포함한 **현시점 전체 실측**. 낮추는 것은 그 18건을
    //        **사용처로 판정한 사람의 몫**이다(A=문맥 키 분리 · B/C=지는 쪽 제거). 올리지 마라.
    //    그 17건(전부 crm2 vs patients2: HSAT (가정용)·검사기록 없음·검사유형·검사일·기공의뢰 없음·
    //      기록일·약물·월령·의뢰유형·접종일·질환 점수·측정법·치료 내용·치아번호·치아차트 없음·
    //      치주 측정 기록 없음·판독의@판독)은 **patients2 소유자가 사용처를 눌러 판정했다**(2026-09-07):
    //      17건 전부 crm2 의 정의가 그 화면 문맥에서도 맞아 **지는 쪽(patients2)을 제거**했다 → B.
    //      같은 라운드에 형식이 다른 카탈로그(`['키', en, ja, ar]` 튜플 행)를 대조 파서가 못 읽어
    //      45건이 더 "신규"로 들어갈 뻔한 것도 같이 걸러냈다 — **대조는 형식을 하나만 가정하면 안 된다.**
    // 🔴 2026-09-07 P2c 합류: 형제들이 신규분까지 정리해 **실측 0**. 17 을 남겨 뒀더니
    //    두 에이전트의 재주입이 **각각 그대로 흡수됐다**(주입 성공을 확인했는데 가드가 초록).
    //    같은 함정을 한 라운드에 두 번 겪었다 — 여유는 0 이다.
    const BASELINE = 0;
    const detail = semantic.map(([k, v]) => `${k}: ${v.map((x) => `${x.area}="${x.en}"`).join(' vs ')}`);
    expect(semantic.length, `의미 충돌 목록:\n${detail.slice(0, 15).join('\n')}`).toBeLessThanOrEqual(BASELINE);
  });

  it('🔴 버튼 동사가 상태 과거분사로 덮이지 않는다 — 품사 오역 회수분(재발 금지)', () => {
    const { conflict } = collect();
    const keys = new Set(conflict.map(([k]) => k));
    // 앞 8건은 '동사(버튼)'와 '상태(라벨)'가 같은 원문을 두고 다투던 자리다.
    // 뒤 22건은 2026-09-07 전수 판정에서 **사용처를 눌러 A(오역)로 확정**한 자리다 —
    //   문맥 키(`@버튼`·`@상태`·`@청구`…)로 분리했거나 이긴 값을 정정했으므로,
    //   **무문맥 키가 다시 서로 다른 번역으로 등재되면 회귀**다(표기 차이도 여기서는 실패다).
    for (const k of [
      '서명', '불출', '반려', '승인', '종료', '조제', '전원', '진행',
      '접수', '퇴원', '완료', '재원', '기록', '진료', '접수 완료', '연락처',
      '비급여', '원내', '사망', '입퇴원', '용량', '활력징후 기록', '접수 대기',
      '혈액검사', '기본', '내용', '미등록', '판정', '외국인 환자 등록', '생성 중...',
    ]) {
      expect(keys.has(k), `'${k}' 가 다시 교차 충돌한다 — 문맥 키로 분리하라`).toBe(false);
    }
  });

  /**
   * 🔴 **en 이 같으면 위 두 가드는 아무것도 못 본다**(2026-09-07 코어 어휘 라운드 실측).
   *    위 가드들은 `en` 값이 **다른** 것만 충돌로 센다. 그런데 en 이 우연히 같아도 정의가 둘이면
   *    다른 언어에서 갈린다 — 실측: 중복 111건 중 en 동일 111, 그중 nav 교차 **7건**.
   *
   *    대표 사례 '수술': nav 는 메뉴(/surgery 모듈), status 는 `CONSENT_TYPE_LABEL`(수술 동의서)였다.
   *    en/ja 는 둘 다 Surgery/手術 라 통했지만 **러시아어는 진료과가 `Хирургия`, 수술 행위가
   *    `Операция`** 다. 팩 번역자는 어느 쪽을 넣어도 한쪽이 틀린다.
   *
   *    메뉴 라벨은 `NAV_SECTIONS` 원문에서 오는 **화면 어휘의 기준점**이고 등록 순서상 거의 항상
   *    이긴다. 그래서 "nav 가 정의한 원문을 다른 영역이 다시 정의하면 그 정의는 죽은 정의"라는
   *    불변식으로 못박는다 — 값이 같아도(=지금 증상이 없어도) 실패한다. 여유 0.
   *    ※ 뜻이 정말 다르면 지우는 게 아니라 `원문@문맥` 으로 가르고 화면도 함께 배선한다.
   */
  it('🔴 메뉴(nav) 원문을 다른 영역이 다시 정의하지 않는다 — en 이 같아도 죽은 정의다', () => {
    const { dup } = collect();
    const navCross = dup
      .filter(([, v]) => v.some((x) => x.area === 'nav'))
      .map(([k, v]) => `${k}: ${v.map((x) => `${x.area}="${x.en}"`).join(' vs ')}`);
    expect(navCross, `nav 교차 중복 — 지는 쪽을 지우거나 문맥 키로 가른다:\n${navCross.join('\n')}`).toEqual([]);
  });

  it('대조군: 중복 키 자체는 정상이다(같은 번역이면 문제 없음)', () => {
    const { dup, conflict } = collect();
    expect(dup.length).toBeGreaterThan(conflict.length); // 중복은 많고 충돌은 그 부분집합
  });
});
