/**
 * 🔴 (2026-09-15 B7) 인라인 @Body 7차 배치 34 핸들러(당직 9·ICU 7·응급 6·간호 5·문서 서명 3·자격 3·병원정보 1) → class DTO 계약.
 * 지키는 것(main.ts 전역 파이프 옵션 그대로):
 *  ① 대조군 — 화면이 **실제로 보내는 키**는 DTO 가 모두 안다(소스에서 키를 뽑아 기계 대조 — whitelist 조용한 삭제 방지)
 *  ② 불리언 위조 — 승인·체크의 문자열 "false" 가 참으로 읽히지 않는다(400)
 *  ③ 행위자 — 문서 서명자·증빙(ipAddress·userAgent)은 본문에서 지워지고, 당직 대리 신청은 비마스터에게 403
 *  ④ 판정 기본값 — SBT 결과·RASS·준수율 없이 기록되지 않는다(종전 PASS·0·100 으로 채워 응답)
 *  ⑤ 어휘 — 자격 상태·콘텐츠 상태·근무·MCI 유형은 스키마/크론이 쓰는 대문자만
 *  ⑥ 핸들러 시그니처가 DTO class 다(소스 대조)
 */
import 'reflect-metadata';
import { ArgumentMetadata, BadRequestException, ForbiddenException } from '@nestjs/common';
import { UserRole } from '@prisma/client';
import { describe, expect, it, vi } from 'vitest';
import { anchorPositions, bodyMeta, dtoKeys, literalKeys, literalKeysFrom, pipe, read } from './dto-contract-helpers';
import {
  DutyAssignDto, DutyAutoGenerateDto, DutyDecisionDto, DutyLeaveRequestDto, DutyOnCallAssignDto, DutyPreferenceDto,
  DutyStaffingRuleDto, DutySwapRequestDto,
} from '../../src/modules/duty-schedule/dto/duty-schedule.dto';
import { DutyScheduleController } from '../../src/modules/duty-schedule/duty-schedule.controller';
import {
  IcuDischargeDto, IcuInfectionBundleDto, IcuSedationDto, IcuSepsisBundleDto, IcuWeaningTrialDto,
} from '../../src/modules/icu/dto/icu-bundle.dto';
import {
  ActivateMciDto, EmergencyCodeAlertDto, EmergencyTreatmentNoteDto, PrenotificationArriveDto,
} from '../../src/modules/emergency/dto/emergency-action.dto';
import {
  CreateNursingChecklistDto, EvaluateNursingOutcomeDto, ToggleNursingChecklistItemDto, UpdateNursingInterventionStatusDto,
} from '../../src/modules/nursing/dto/nursing-checklist-write.dto';
import { InitMultiSignDto, SignDocumentDto, VerifySignedDocumentDto } from '../../src/modules/document-sign/dto/document-sign.dto';
import {
  CreateStaffCredentialDto, RecordStaffEducationDto, UpdateStaffCredentialStatusDto,
} from '../../src/modules/staff-qualification/dto/staff-qualification-write.dto';
import { UpdateHospitalInfoStatusDto } from '../../src/modules/hospital-info/hospital-info.controller';

const bad = (v: unknown, t: ArgumentMetadata['metatype']) => expect(pipe.transform(v, bodyMeta(t))).rejects.toBeInstanceOf(BadRequestException);
const ok = (v: unknown, t: ArgumentMetadata['metatype']) => pipe.transform(v, bodyMeta(t)) as Promise<Record<string, unknown>>;
const U = '11111111-1111-4111-8111-111111111111';
const U2 = '22222222-2222-4222-8222-222222222222';

describe('B7 요청 본문 DTO 계약', () => {
  describe('① 화면이 보내는 키를 DTO 가 모두 안다(whitelist 조용한 삭제 방지)', () => {
    const ADMIN_DUTY = 'apps/web/src/app/(main)/admin/duty-schedule/page.tsx';
    const cases: Array<[string, string, string[], new () => object]> = [
      [ADMIN_DUTY, "apiClient.post('/api/v1/duty/auto-generate',", ['month', 'department', 'constraints'], DutyAutoGenerateDto],
      [ADMIN_DUTY, "apiClient.post('/api/v1/duty/assign',", ['date', 'shift', 'staffId'], DutyAssignDto],
      [ADMIN_DUTY, 'const [oc, setOc] = useState(', ['date', 'department', 'callLevel', 'staffId'], DutyOnCallAssignDto],
      [ADMIN_DUTY, 'const [sr, setSr] = useState(', ['department', 'shift', 'dayType', 'minCount'], DutyStaffingRuleDto],
      ['apps/web/src/app/(main)/duty-schedule/page.tsx', 'autoGenMut.mutate(', ['month', 'department', 'constraints'], DutyAutoGenerateDto],
      ['apps/web/src/app/(main)/inpatient/[admissionId]/nursing/checklist/page.tsx', '/checklists`,', ['templateType'], CreateNursingChecklistDto],
      ['apps/web/src/app/(main)/inpatient/[admissionId]/nursing/checklist/page.tsx', '/items/${index}`,', ['checked'], ToggleNursingChecklistItemDto],
      ['apps/web/src/app/(main)/inpatient/[admissionId]/nursing/care-plan/page.tsx', '/nursing-interventions/${id}`,', ['status'], UpdateNursingInterventionStatusDto],
      ['apps/web/src/app/(main)/inpatient/[admissionId]/nursing/care-plan/page.tsx', '/evaluate`,', ['currentScore'], EvaluateNursingOutcomeDto],
      ['apps/web/src/app/(main)/workstation/emergency/page.tsx', "apiClient.post('/api/v1/emergency/code-alert',", ['code', 'location'], EmergencyCodeAlertDto],
      ['apps/web/src/app/(main)/emergency/page.tsx', '/treatment`,', ['note'], EmergencyTreatmentNoteDto],
      ['apps/web/src/app/(main)/emergency-board/page.tsx', "apiClient.post('/api/v1/emergency/mci/activate',", ['title', 'expectedCasualties'], ActivateMciDto],
    ];
    for (const [file, anchor, expected, dto] of cases) {
      it(`${file.split('/').slice(-2).join('/')} ${anchor.slice(0, 40)} → ${dto.name}`, () => {
        const sent = literalKeys(read(file), anchor);
        // 추출기 자체 대조군 — 알려진 키를 실제로 뽑았는가(추출이 비면 아래 검사는 증거가 아니다)
        expect([...sent].sort()).toEqual([...expected].sort());
        const known = dtoKeys(dto);
        expect(sent.filter((k) => !known.has(k))).toEqual([]);
      });
    }

    it('자격·교육 등록 폼(`/admin/sqe`) 두 useState 의 키 = DTO 가 아는 키 · 빈 날짜 `""` 는 미입력으로 통과', async () => {
      const src = read('apps/web/src/app/(main)/admin/sqe/page.tsx');
      const anchor = 'const [form, setForm] = useState(';
      const [credAt, eduAt] = anchorPositions(src, anchor);
      const credKeys = literalKeysFrom(src, credAt + anchor.length);
      const eduKeys = literalKeysFrom(src, eduAt + anchor.length);
      expect([...credKeys].sort()).toEqual(['expiresAt', 'issuer', 'name', 'number', 'type', 'userId']);
      expect([...eduKeys].sort()).toEqual(['category', 'completedAt', 'courseName', 'expiresAt', 'userId']);
      expect(credKeys.filter((k) => !dtoKeys(CreateStaffCredentialDto).has(k))).toEqual([]);
      expect(eduKeys.filter((k) => !dtoKeys(RecordStaffEducationDto).has(k))).toEqual([]);
      await expect(ok({ userId: U, type: 'LICENSE', name: '의사면허', number: '', issuer: '', expiresAt: '' }, CreateStaffCredentialDto))
        .resolves.toMatchObject({ expiresAt: '' });
      await expect(ok({ userId: U, courseName: '감염관리', category: 'MANDATORY', completedAt: '', expiresAt: '' }, RecordStaffEducationDto))
        .resolves.toMatchObject({ completedAt: '' });
      await bad({ userId: U, type: 'LICENSE', name: '의사면허', expiresAt: 'garbage' }, CreateStaffCredentialDto);
    });

    it('문서 서명 모달 — 두 제출 경로(생체·PIN)의 키를 DTO 가 모두 안다', () => {
      const src = read('apps/web/src/components/signature/SignatureModal.tsx');
      const anchor = "('/api/v1/document-sign/sign',";
      const positions = anchorPositions(src, anchor);
      expect(positions).toHaveLength(2);
      for (const at of positions) {
        const sent = literalKeysFrom(src, at + anchor.length);
        expect([...sent].sort()).toEqual([
          'certificateId', 'documentHash', 'documentId', 'documentType', 'patientId', 'signatureAlgorithm',
          'signatureValue', 'signerRole', 'signerType', 'signerUserId', // signerPatientId 는 보내지 않는다(U2 — 직원 인증서 서명)
        ]);
        expect(sent.filter((k) => !dtoKeys(SignDocumentDto).has(k))).toEqual([]);
      }
    });

    it('화면 본문 모양 통과 — 당직·ICU 퇴실(`{}`)·도착 처리·다중 서명', async () => {
      await expect(ok({ month: '2026-09', department: '', constraints: { maxConsecutiveNights: 3, maxWeeklyHours: 52, minRestHours: 11 } }, DutyAutoGenerateDto)).resolves.toBeTruthy();
      await expect(ok({ month: '2026-09', department: '전체', constraints: { maxConsecutiveNights: 3, maxWeeklyHours: 80, minRestHours: 8 } }, DutyAutoGenerateDto)).resolves.toBeTruthy();
      await expect(ok({ date: '2026-09-16', department: '내과', callLevel: 'FIRST', staffId: U }, DutyOnCallAssignDto)).resolves.toBeTruthy();
      await expect(ok({ department: '내과', shift: 'DAY', dayType: 'ALL', minCount: 1 }, DutyStaffingRuleDto)).resolves.toBeTruthy();
      await expect(ok({}, IcuDischargeDto)).resolves.toBeTruthy();
      await expect(ok({}, PrenotificationArriveDto)).resolves.toBeTruthy();
      await expect(ok({ signedDocumentId: U }, VerifySignedDocumentDto)).resolves.toBeTruthy();
      await expect(ok({ documentType: 'CONSENT', documentId: U, documentHash: 'h', requiredSigners: 2 }, InitMultiSignDto)).resolves.toBeTruthy();
      await bad({ documentType: 'CONSENT', documentId: U, documentHash: 'h', requiredSigners: 1 }, InitMultiSignDto);
    });
  });

  describe('② 불리언 위조 — 문자열 "false" 는 참이 아니다', () => {
    it('🔴 당직 교대·휴가 승인 `approve: "false"` 는 400(종전: 참으로 읽혀 승인)', async () => {
      await bad({ approve: 'false' }, DutyDecisionDto);
      await bad({}, DutyDecisionDto);
      await expect(ok({ approve: false }, DutyDecisionDto)).resolves.toEqual({ approve: false });
    });
    it('🔴 간호 체크리스트 `checked: "false"` 는 400(종전: 체크되고 완료 시각까지 찍힘)', async () => {
      await bad({ checked: 'false' }, ToggleNursingChecklistItemDto);
      await expect(ok({ checked: false }, ToggleNursingChecklistItemDto)).resolves.toEqual({ checked: false });
    });
  });

  describe('③ 행위자는 본문이 정하지 않는다', () => {
    it('🔴 문서 서명 — 본문의 ipAddress·userAgent 는 지워진다 · 컨트롤러가 인증 주체·요청 연결을 넘긴다', async () => {
      const r = await ok({
        documentType: 'CONSENT', documentId: U, documentHash: 'h', certificateId: U2, signatureValue: 'v',
        signatureAlgorithm: 'ECDSA_P256', signerRole: 'PRIMARY', signerType: 'STAFF', ipAddress: '6.6.6.6', userAgent: 'forged',
      }, SignDocumentDto);
      expect(r).not.toHaveProperty('ipAddress');
      expect(r).not.toHaveProperty('userAgent');
      await bad({ documentType: 'CONSENT', documentId: U, documentHash: 'h', certificateId: U2, signatureValue: 'v', signatureAlgorithm: 'A', signerRole: 'R', signerType: 'ROBOT' }, SignDocumentDto);
      const ctl = read('apps/api/src/modules/document-sign/document-sign.controller.ts').replace(/\/\/[^\n]*/g, '');
      const sign = ctl.slice(ctl.indexOf('async sign('), ctl.indexOf('async verify('));
      expect(sign).toMatch(/\{ userId, ipAddress: req\?\.ip/);
      expect(sign).not.toMatch(/signerUserId: body/);
      expect(sign).not.toMatch(/\.\.\.body/);
    });

    const svc = () => ({ requestSwap: vi.fn().mockResolvedValue({}), requestLeave: vi.fn().mockResolvedValue({}), upsertPreference: vi.fn().mockResolvedValue({}) });
    it('🔴 당직 교대·휴가·선호 — 비마스터(DOCTOR)가 타인 명의로 신청하면 403 · 서비스에 닿지 않는다', async () => {
      const s = svc();
      const c = new DutyScheduleController(s as never);
      const swap = { requesterId: U2, targetId: U, originalDate: '2026-09-16', originalShift: 'DAY', swapDate: '2026-09-17', swapShift: 'NIGHT', reason: 'x' };
      await expect(c.requestSwap(swap as DutySwapRequestDto, U, UserRole.DOCTOR)).rejects.toBeInstanceOf(ForbiddenException);
      const leave = { staffId: U2, startDate: '2026-09-16', endDate: '2026-09-17', type: 'ANNUAL', reason: 'x' };
      await expect(c.requestLeave(leave as DutyLeaveRequestDto, U, UserRole.DOCTOR)).rejects.toBeInstanceOf(ForbiddenException);
      const pref = { staffId: U2, month: '2026-09', date: '2026-09-16', kind: 'AVOID' };
      await expect(c.upsertPref(pref as DutyPreferenceDto, U, UserRole.DOCTOR)).rejects.toBeInstanceOf(ForbiddenException);
      expect(s.requestSwap).not.toHaveBeenCalled();
      expect(s.requestLeave).not.toHaveBeenCalled();
      expect(s.upsertPreference).not.toHaveBeenCalled();
    });
    it('대조군 — 본인 명의는 누구나 · 타인 명의는 근무표 마스터(NURSE·ADMIN)만', async () => {
      const s = svc();
      const c = new DutyScheduleController(s as never);
      const swap = { requesterId: U, targetId: U2, originalDate: '2026-09-16', originalShift: 'DAY', swapDate: '2026-09-17', swapShift: 'NIGHT', reason: 'x' } as DutySwapRequestDto;
      await c.requestSwap(swap, U, UserRole.DOCTOR);
      await c.requestSwap({ ...swap, requesterId: U2 }, U, UserRole.NURSE);
      await c.upsertPref({ staffId: U2, month: '2026-09', date: '2026-09-16', kind: 'AVOID' } as DutyPreferenceDto, U, UserRole.ADMIN);
      expect(s.requestSwap).toHaveBeenCalledTimes(2);
      expect(s.upsertPreference).toHaveBeenCalledTimes(1);
    });
  });

  describe('④ 판정 없이 기록되지 않는다(서비스 기본값 PASS·0·100 에 닿지 않게)', () => {
    it('🔴 SBT 결과·RASS·감염 번들 준수율·패혈증 번들 종류는 필수', async () => {
      await bad({ method: 'T-piece' }, IcuWeaningTrialDto);
      await bad({ result: 'pass' }, IcuWeaningTrialDto);
      await expect(ok({ result: 'FAIL', failureReason: 'RR>35' }, IcuWeaningTrialDto)).resolves.toMatchObject({ result: 'FAIL' });
      await bad({ bps: 4 }, IcuSedationDto);
      await bad({ rass: 5 }, IcuSedationDto);
      await expect(ok({ rass: -2, camIcu: false }, IcuSedationDto)).resolves.toMatchObject({ rass: -2 });
      await bad({ bundleType: 'VAP' }, IcuInfectionBundleDto);
      await expect(ok({ bundleType: 'VAP', complianceRate: 80 }, IcuInfectionBundleDto)).resolves.toBeTruthy();
      await bad({ lactateOrdered: true }, IcuSepsisBundleDto);
    });
  });

  describe('⑤ 어휘·형식', () => {
    it('자격 상태·콘텐츠 상태·근무·MCI 유형·결과 점수', async () => {
      await bad({ status: 'valid' }, UpdateStaffCredentialStatusDto);
      await expect(ok({ status: 'SUSPENDED' }, UpdateStaffCredentialStatusDto)).resolves.toBeTruthy();
      await bad({ status: 'published' }, UpdateHospitalInfoStatusDto);
      await bad({ status: 'PUBLISHED', publishFrom: 'soon' }, UpdateHospitalInfoStatusDto);
      await expect(ok({ status: 'SCHEDULED', publishFrom: '2026-09-20T00:00:00+09:00' }, UpdateHospitalInfoStatusDto)).resolves.toBeTruthy();
      await bad({ date: '2026-09-16', shift: 'MORNING', staffId: U }, DutyAssignDto);
      await bad({ date: '16/09/2026', shift: 'DAY', staffId: U }, DutyAssignDto);
      await bad({ title: '다중 추돌', type: 'mci' }, ActivateMciDto);
      await bad({ title: '다중 추돌', expectedCasualties: 2.5 }, ActivateMciDto);
      await bad({ code: '' }, EmergencyCodeAlertDto);
      await bad({ visitId: 'visit-1' }, PrenotificationArriveDto);
      await bad({ currentScore: '70' }, EvaluateNursingOutcomeDto);
      await bad({ status: 'DONE' }, UpdateNursingInterventionStatusDto);
      await bad({ templateType: 'SHIFT_HANDOFF', shiftType: 'MORNING' }, CreateNursingChecklistDto);
    });
  });

  it('⑥ 핸들러 시그니처가 DTO class 다', () => {
    const duty = read('apps/api/src/modules/duty-schedule/duty-schedule.controller.ts');
    expect(duty).not.toMatch(/@Body\(\) body: \{/);
    expect(duty.match(/assertSelfOrMaster\(body\.(requesterId|staffId), callerId, callerRole\)/g)).toHaveLength(3);
    const icu = read('apps/api/src/modules/icu/icu.controller.ts');
    expect(icu).not.toMatch(/@Body\(\) body\??: (Record<|\{)/);
    const ds = read('apps/api/src/modules/document-sign/document-sign.controller.ts');
    expect(ds).not.toMatch(/@Body\(\s*'/);
    expect(ds).not.toMatch(/Record<string, unknown>/);
    const nursing = read('apps/api/src/modules/nursing/nursing.controller.ts');
    expect(nursing).not.toMatch(/@Body\('(status|note|currentScore)'\)/);
    const er = read('apps/api/src/modules/emergency/emergency.controller.ts');
    expect(er).not.toMatch(/@Body\(\) body: \{/);
    const sq = read('apps/api/src/modules/staff-qualification/staff-qualification.controller.ts');
    expect(sq).not.toMatch(/@Body\(\) body: \{/);
    expect(read('apps/api/src/modules/hospital-info/hospital-info.controller.ts')).toMatch(/@Body\(\) dto: UpdateHospitalInfoStatusDto/);
  });
});
