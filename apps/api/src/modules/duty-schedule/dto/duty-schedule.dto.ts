import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsBoolean, IsIn, IsInt, IsNotEmpty, IsOptional, IsString, IsUUID, Matches, Max, MaxLength, Min, ValidateNested,
} from 'class-validator';

/**
 * 🔴 (2026-09-15 B7) 당직 쓰기 9 핸들러가 인라인 타입(`{ approve: boolean }` 등)이라 ValidationPipe 가 통째로 스킵됐다.
 *  - 승인/거절 `approve` 는 문자열 `"false"` 도 참으로 읽혀 **거절을 누르면 승인**될 수 있었다(IsBoolean).
 *  - 교대·휴가·선호의 행위자(`requesterId`·`staffId`)는 본문에서 왔다 — 비마스터의 대리 신청은 컨트롤러가 막는다
 *    (같은 컨트롤러의 근무시간 조회 규칙 "본인 것은 누구나, 타인 것은 근무표 마스터"를 쓰기에도 적용).
 * 어휘는 스키마 주석·서비스 타입에 이미 적힌 것만 쓴다(근무 DAY·EVENING·NIGHT · 휴가 · on-call 등급 · 인력기준 요일 · 선호 종류).
 * 날짜는 스키마가 `VarChar(10)` 문자열(YYYY-MM-DD)·월은 `VarChar(7)`(YYYY-MM).
 */
const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;
const MONTH = /^\d{4}-\d{2}$/;
export const DUTY_SHIFTS = ['DAY', 'EVENING', 'NIGHT'] as const;
export const DUTY_LEAVE_TYPES = ['ANNUAL', 'SICK', 'PERSONAL', 'MATERNITY'] as const;
export const DUTY_CALL_LEVELS = ['FIRST', 'SECOND', 'BACKUP'] as const;
export const DUTY_DAY_TYPES = ['ALL', 'WEEKDAY', 'WEEKEND', 'HOLIDAY'] as const;
export const DUTY_PREFERENCE_KINDS = ['WISH_OFF', 'WISH_DAY', 'WISH_NIGHT', 'AVOID'] as const;

export class DutyAutoGenerateConstraintsDto {
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(1) @Max(31) maxConsecutiveNights?: number;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(1) @Max(168) maxWeeklyHours?: number;
  @ApiPropertyOptional() @IsOptional() @IsInt() @Min(0) @Max(48) minRestHours?: number;
}

export class DutyAutoGenerateDto {
  @ApiProperty({ description: 'YYYY-MM' }) @IsString() @Matches(MONTH) month!: string;
  /** 관리 화면은 전체를 `''`, 당직 화면은 `'전체'` 로 보낸다 — 둘 다 받는다(서비스 해석은 기존 그대로) */
  @ApiProperty() @IsString() @MaxLength(50) department!: string;
  @ApiPropertyOptional({ type: DutyAutoGenerateConstraintsDto })
  @IsOptional() @ValidateNested() @Type(() => DutyAutoGenerateConstraintsDto)
  constraints?: DutyAutoGenerateConstraintsDto;
}

export class DutyAssignDto {
  @ApiProperty({ description: 'YYYY-MM-DD' }) @IsString() @Matches(DATE_ONLY) date!: string;
  @ApiProperty({ enum: DUTY_SHIFTS }) @IsIn(DUTY_SHIFTS) shift!: (typeof DUTY_SHIFTS)[number];
  @ApiProperty() @IsUUID() staffId!: string;
}

export class DutySwapRequestDto {
  @ApiProperty() @IsUUID() requesterId!: string;
  @ApiProperty() @IsUUID() targetId!: string;
  @ApiProperty() @IsString() @Matches(DATE_ONLY) originalDate!: string;
  @ApiProperty({ enum: DUTY_SHIFTS }) @IsIn(DUTY_SHIFTS) originalShift!: string;
  @ApiProperty() @IsString() @Matches(DATE_ONLY) swapDate!: string;
  @ApiProperty({ enum: DUTY_SHIFTS }) @IsIn(DUTY_SHIFTS) swapShift!: string;
  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(1000) reason!: string;
}

export class DutyDecisionDto {
  /** 🔴 문자열 `"false"` 는 400 — 종전엔 참으로 읽혀 승인됐다 */
  @ApiProperty() @IsBoolean() approve!: boolean;
}

export class DutyLeaveRequestDto {
  @ApiProperty() @IsUUID() staffId!: string;
  @ApiProperty() @IsString() @Matches(DATE_ONLY) startDate!: string;
  @ApiProperty() @IsString() @Matches(DATE_ONLY) endDate!: string;
  @ApiProperty({ enum: DUTY_LEAVE_TYPES }) @IsIn(DUTY_LEAVE_TYPES) type!: (typeof DUTY_LEAVE_TYPES)[number];
  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(1000) reason!: string;
}

export class DutyStaffingRuleDto {
  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(50) department!: string;
  @ApiProperty({ enum: DUTY_SHIFTS }) @IsIn(DUTY_SHIFTS) shift!: string;
  @ApiPropertyOptional({ enum: DUTY_DAY_TYPES }) @IsOptional() @IsIn(DUTY_DAY_TYPES) dayType?: string;
  @ApiProperty() @IsInt() @Min(0) @Max(999) minCount!: number;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(10) nurseGrade?: string;
}

export class DutyOnCallAssignDto {
  @ApiProperty({ description: 'YYYY-MM-DD' }) @IsString() @Matches(DATE_ONLY) date!: string;
  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(50) department!: string;
  @ApiProperty({ enum: DUTY_CALL_LEVELS }) @IsIn(DUTY_CALL_LEVELS) callLevel!: string;
  @ApiProperty() @IsUUID() staffId!: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(200) note?: string;
}

export class DutyPreferenceDto {
  @ApiProperty() @IsUUID() staffId!: string;
  @ApiProperty({ description: 'YYYY-MM' }) @IsString() @Matches(MONTH) month!: string;
  @ApiProperty({ description: 'YYYY-MM-DD' }) @IsString() @Matches(DATE_ONLY) date!: string;
  @ApiProperty({ enum: DUTY_PREFERENCE_KINDS }) @IsIn(DUTY_PREFERENCE_KINDS) kind!: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(200) note?: string;
}
