import { Controller, Get, Post, Patch, Delete, Param, Query, Body, UseGuards, BadRequestException, ForbiddenException, Optional } from '@nestjs/common';
import { ApiTags, ApiBearerAuth, ApiOperation } from '@nestjs/swagger';
import { DutyScheduleService } from './duty-schedule.service';
import { ConfigRuntimeService } from '../config/config-runtime.service';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { Roles } from '../../common/decorators/roles.decorator';
import { CurrentUser } from '../../common/decorators/current-user.decorator';
import { UserRole } from '@prisma/client';
import { RolesGuard } from '../auth/guards/roles.guard';
import {
  DutyAssignDto, DutyAutoGenerateDto, DutyDecisionDto, DutyLeaveRequestDto, DutyOnCallAssignDto, DutyPreferenceDto,
  DutyStaffingRuleDto, DutySwapRequestDto,
} from './dto/duty-schedule.dto';

/**
 * 🔴 W7(2026-08) 인가 봉합 — 읽기 EP 8종(schedule·hours·violations·on-call·stats·fairness·
 *    staffing-rules(GET)·oncall-roster(GET))에 `@Roles` 가 없었다. RolesGuard 는 role·permission
 *    이 둘 다 없으면 **통과**시키므로, 인증만 되면 RECEPTIONIST·NUTRITION·READ 등 전 역할이
 *    전 직원 근무표와 개인별 근무시간(인사정보)을 열람할 수 있었다. 같은 컨트롤러의 쓰기 EP 는
 *    이미 배선돼 있었다 — 보호가 반쪽이면 없는 것과 같다.
 *
 * 근무표 열람 역할 = 당직 대상 직군(DOCTOR·NURSE) + 관리자. 쓰기 역할 집합과 일치시켰다.
 * (ADMIN 은 RolesGuard 설계상 항상 통과하지만, 의도를 문서화하기 위해 명시한다)
 */
const DUTY_READERS = [UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR] as const;

/** 근무표 마스터 — 타인 근무시간까지 볼 수 있는 역할(쓰기 마스터와 동일 집합) */
const DUTY_MASTER_ROLES: readonly UserRole[] = [UserRole.ADMIN, UserRole.NURSE];

/**
 * 🔴 (2026-09-15 B7) 교대·휴가·선호의 행위자는 본문(`requesterId`·`staffId`)에서 왔다 — 당직 대상 직군이면
 *    누구나 **남의 이름으로** 교대를 요청하고 휴가를 신청할 수 있었다. 근무시간 조회(`hours/:userId`)와 같은 규칙:
 *    본인 것은 누구나, 타인 것은 근무표 마스터(관리자·간호관리자)만. 문구는 고정 문장(코드로 구분).
 */
function assertSelfOrMaster(subjectId: string, callerId: string, callerRole: UserRole): void {
  if (subjectId !== callerId && !DUTY_MASTER_ROLES.includes(callerRole)) {
    throw new ForbiddenException({
      code: 'DUTY_SELF_ONLY',
      message: '타인 명의의 신청은 근무표 마스터(관리자·간호관리자)만 할 수 있습니다',
    });
  }
}

@ApiTags('Duty Schedule (당직 관리)')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard, RolesGuard)
@Controller('api/v1/duty')
export class DutyScheduleController {
  constructor(private readonly service: DutyScheduleService, @Optional() private readonly configRuntime?: ConfigRuntimeService) {}

  /* ── 1. 월간 당직표 조회 ────────────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: @Roles 부재로 전 역할이 전 직원 근무표를 열람하던 것
  @Get('schedule')
  @ApiOperation({ summary: '월간 당직표 조회' })
  async getSchedule(
    @Query('month') month?: string,
    @Query('department') department?: string,
  ) {
    const m = month ?? `${new Date().getFullYear()}-${String(new Date().getMonth() + 1).padStart(2, '0')}`;
    return { ok: true, data: await this.service.getSchedule(m, department), timestamp: new Date().toISOString() };
  }

  /* ── 2. 당직 자동 생성 ─────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Post('auto-generate')
  @ApiOperation({ summary: '당직 자동 생성 (제약 조건 기반)' })
  async autoGenerate(
    @Body() body: DutyAutoGenerateDto,
  ) {
    const result = await this.service.autoGenerate(
      body.month,
      body.department,
      body.constraints ?? {},
    );
    return { ok: true, data: result, timestamp: new Date().toISOString() };
  }

  /* ── 3. 수동 배정 ──────────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Post('assign')
  @ApiOperation({ summary: '당직 수동 배정' })
  async assign(
    @Body() body: DutyAssignDto,
  ) {
    const result = await this.service.assign(body);
    return { ok: true, ...result, timestamp: new Date().toISOString() };
  }

  /* ── 4. 교대 요청 ──────────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR) // 당직 대상 직군만 — 비당직 역할 위조 차단
  @Post('swap-request')
  @ApiOperation({ summary: '당직 교대 요청' })
  async requestSwap(
    @Body() body: DutySwapRequestDto,
    @CurrentUser('id') callerId: string,
    @CurrentUser('role') callerRole: UserRole,
  ) {
    assertSelfOrMaster(body.requesterId, callerId, callerRole);
    const result = await this.service.requestSwap(body);
    return { ok: true, ...result, timestamp: new Date().toISOString() };
  }

  /* ── 5. 교대 승인/거절 ─────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Patch('swap-request/:id')
  @ApiOperation({ summary: '교대 요청 승인/거절' })
  async handleSwap(
    @Param('id') id: string,
    @Body() body: DutyDecisionDto,
  ) {
    const result = await this.service.handleSwap(id, body.approve);
    return { ok: true, ...result, timestamp: new Date().toISOString() };
  }

  /* ── 6. 주간 근무시간 조회 ─────────────── */
  // 🔴 W7: @Roles 부재 + 타인 지정 조회(:userId) — 인증만 되면 아무나 특정 직원의 주간 근무시간을
  //    볼 수 있었다. 본인 것은 누구나, 타인 것은 근무표 마스터(ADMIN·NURSE)만으로 좁힌다.
  //    DutyEntry.staffId = User.id 이므로 @CurrentUser('id') 와 직접 대조 가능하다.
  @Roles(...DUTY_READERS)
  @Get('hours/:userId')
  @ApiOperation({ summary: '주간 근무시간 조회 (본인 또는 근무표 마스터)' })
  async getHours(
    @Param('userId') userId: string,
    @CurrentUser('id') requesterId: string,
    @CurrentUser('role') requesterRole: UserRole,
    @Query('weekStart') weekStart?: string,
  ) {
    if (userId !== requesterId && !DUTY_MASTER_ROLES.includes(requesterRole)) {
      throw new ForbiddenException({
        code: 'DUTY_HOURS_SELF_ONLY',
        message: '타인의 근무시간은 근무표 마스터(관리자·간호관리자)만 조회할 수 있습니다',
      });
    }
    const ws = weekStart ?? (() => {
      const d = new Date();
      d.setDate(d.getDate() - d.getDay());
      return d.toISOString().split('T')[0];
    })();
    return { ok: true, data: await this.service.getHours(userId, ws), timestamp: new Date().toISOString() };
  }

  /* ── 7. 80시간 초과 위반 목록 ──────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: 전 직원 근로시간 위반 명단(인사정보)이 무제한 열람되던 것
  @Get('violations')
  @ApiOperation({ summary: '주 80시간 초과 위반 목록' })
  async getViolations() {
    return { ok: true, data: await this.service.getViolations(), timestamp: new Date().toISOString() };
  }

  /* ── 8. 오늘 당직자 조회 ───────────────── */
  // 🔴 W7: @Roles 부재. 현재 호출 화면이 없어 최소권한(당직 대상 직군+관리자)으로 닫는다 —
  //    원무·응급 접수가 당직의 확인을 필요로 하면 그때 역할을 넓힌다(운영 판단).
  @Roles(...DUTY_READERS)
  @Get('on-call')
  @ApiOperation({ summary: '오늘 당직자 조회' })
  async getOnCall(@Query('date') date?: string) {
    return { ok: true, data: await this.service.getOnCall(date), timestamp: new Date().toISOString() };
  }

  /* ── 9. 휴가 신청 ──────────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR) // 당직 대상 직군만 — 비당직 역할 위조 차단
  @Post('leave-request')
  @ApiOperation({ summary: '휴가 신청' })
  async requestLeave(
    @Body() body: DutyLeaveRequestDto,
    @CurrentUser('id') callerId: string,
    @CurrentUser('role') callerRole: UserRole,
  ) {
    assertSelfOrMaster(body.staffId, callerId, callerRole);
    // 휴가 경로 단일화(P0-3, config ess.leave.unified) — ESS 전자결재 경로로 통합, 이 경로는 신규 생성 중단
    const unified = String((await this.configRuntime?.get('ess.leave.unified').catch(() => null)) ?? 'false') === 'true';
    if (unified) {
      throw new BadRequestException({
        code: 'LEAVE_PATH_UNIFIED',
        message: '휴가 신청은 내 행정(ESS)으로 통합되었습니다 — /staff/ess의 휴가 탭에서 신청하세요(전자결재 연동)',
      });
    }
    const result = await this.service.requestLeave(body);
    return { ok: true, ...result, timestamp: new Date().toISOString() };
  }

  /* ── 10. 휴가 승인/거절 ────────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Patch('leave-request/:id')
  @ApiOperation({ summary: '휴가 신청 승인/거절' })
  async handleLeave(
    @Param('id') id: string,
    @Body() body: DutyDecisionDto,
  ) {
    const result = await this.service.handleLeave(id, body.approve);
    return { ok: true, ...result, timestamp: new Date().toISOString() };
  }

  /* ── 11. 당직 통계 ─────────────────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: 부서별/개인별 당직 통계(인사정보)가 무제한 열람되던 것
  @Get('stats')
  @ApiOperation({ summary: '당직 통계 (부서별/개인별)' })
  async getStats(@Query('month') month?: string) {
    return { ok: true, data: await this.service.getStats(month), timestamp: new Date().toISOString() };
  }

  /* ── 12. 공정성 리포트 ─────────────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: 개인별 당직 편중(인사평가성 지표)이 무제한 열람되던 것
  @Get('fairness')
  @ApiOperation({ summary: '공정성 리포트 (표준편차 기반)' })
  async getFairnessReport(@Query('month') month?: string) {
    return { ok: true, data: await this.service.getFairnessReport(month), timestamp: new Date().toISOString() };
  }

  /* ── 13. 인력기준(P1b) ─────────────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: 쓰기(POST/DELETE)만 막혀 있고 조회는 열려 있던 것
  @Get('staffing-rules')
  @ApiOperation({ summary: '당직 인력기준 조회(부서·근무·요일별 최소인원)' })
  async listStaffing(@Query('department') department?: string) {
    return { ok: true, data: await this.service.listStaffingRules(department), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Post('staffing-rules')
  @ApiOperation({ summary: '당직 인력기준 등록/수정' })
  async upsertStaffing(@Body() body: DutyStaffingRuleDto) {
    return { ok: true, data: await this.service.upsertStaffingRule(body), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Delete('staffing-rules/:id')
  @ApiOperation({ summary: '당직 인력기준 삭제' })
  async deleteStaffing(@Param('id') id: string) {
    return { ok: true, data: await this.service.deleteStaffingRule(id), timestamp: new Date().toISOString() };
  }

  /* ── 14. 당직 on-call(P2) ─────────────── */
  @Roles(...DUTY_READERS) // 🔴 W7: 쓰기(POST/DELETE)만 막혀 있고 조회는 열려 있던 것
  @Get('oncall-roster')
  @ApiOperation({ summary: '당직(on-call) 조회 — 과별 1st/2nd call' })
  async listOnCall(@Query('month') month?: string, @Query('department') department?: string) {
    return { ok: true, data: await this.service.listOnCall(month, department), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 관리자·간호관리자만(2026-07 RBAC 전수)
  @Post('oncall-roster')
  @ApiOperation({ summary: '당직(on-call) 배정' })
  async assignOnCall(@Body() body: DutyOnCallAssignDto) {
    return { ok: true, data: await this.service.assignOnCall(body), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE) // 근무표 마스터 — 무가드 봉합(2026-08 nav↔API 감사)
  @Delete('oncall-roster/:id')
  @ApiOperation({ summary: '당직(on-call) 삭제' })
  async removeOnCall(@Param('id') id: string) {
    return { ok: true, data: await this.service.removeOnCall(id), timestamp: new Date().toISOString() };
  }

  /* ── 15. 개인 근무 선호(P3) ─────────────── */
  @Roles(UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR) // 쓰기 형제와 일치 — 비당직 역할의 타 직원 선호 조회 차단
  @Get('preferences')
  @ApiOperation({ summary: '근무 선호/기피 조회' })
  async listPref(@Query('month') month: string, @Query('staffId') staffId?: string) {
    return { ok: true, data: await this.service.listPreferences(month, staffId), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR) // 당직 대상 직군만 — 비당직 역할 위조 차단
  @Post('preferences')
  @ApiOperation({ summary: '근무 선호/기피 등록' })
  async upsertPref(
    @Body() body: DutyPreferenceDto,
    @CurrentUser('id') callerId: string,
    @CurrentUser('role') callerRole: UserRole,
  ) {
    assertSelfOrMaster(body.staffId, callerId, callerRole);
    return { ok: true, data: await this.service.upsertPreference(body), timestamp: new Date().toISOString() };
  }

  @Roles(UserRole.ADMIN, UserRole.NURSE, UserRole.DOCTOR) // 당직 대상 직군만 — 비당직 역할 위조 차단
  @Delete('preferences/:id')
  @ApiOperation({ summary: '근무 선호 삭제' })
  async removePref(@Param('id') id: string) {
    return { ok: true, data: await this.service.removePreference(id), timestamp: new Date().toISOString() };
  }
}
