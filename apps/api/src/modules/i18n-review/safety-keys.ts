/**
 * 안전 키 판정 — **오역이 임상·규제 위해가 되는 자리** (정본 `i18n-human-review.plan.md` §2.4).
 *
 * 🔴 **정규식은 여기 한 곳에만 둔다.** 화면·서버·가드가 각자 목록을 들면 갈라진다(P12).
 *    수기 키 목록도 두지 않는다 — 카탈로그가 늘 때마다 낡고, 새 안전 키가 조용히 시야 밖이 된다.
 *    패턴이면 **새 키가 자동으로 시야에 든다**(`i18n-unwired-scan.mjs` 의 SAFETY_PATH 와 같은 원칙).
 *
 * 🔴 이 판정은 **과탐 쪽으로 기운다** — 안전 키를 놓치는 것(미탐)이 위해이고,
 *    안전 키가 아닌 것을 안전 키라 부르는 것(과탐)은 검수 순서가 앞당겨질 뿐이다.
 *    화면은 "안전 키 후보"가 아니라 배지로 보여주되, 판정 근거(`reason`)를 함께 준다.
 *
 * 🔴 이것은 **분류이지 강제가 아니다** — 안전 키를 번역하지 않고 원문+티로 두는 것도 정답이다
 *    (KTAS 등급·MAR 상태·혈액제제 선례). 검수자가 `REJECTED` + 사유로 그 선택을 남긴다.
 *
 * 근거(각 항목이 실제로 이 저장소에서 문제가 됐거나 카탈로그 헤더가 검수 대상으로 열거한 축):
 *  · 위급값·경보    — `lab_critical_flag`(HH·LL 누수)·거짓 경보가 진짜 경보를 죽인다
 *  · KTAS·중증도    — 태국어 팩이 **입원 결정 환자를 퇴원 대기로** 옮겨 적은 선례(v4.16.0)
 *  · 투약·MAR·용량  — 5-Rights·처방 '1정' 날조 선례
 *  · 혈액제제·수혈  — 6개 팩이 **독립적으로 제외**한 어휘(한·중 제품 구분 상이)
 *  · 연하곤란 질감  — 오역이 흡인 사고(vi·kk·th 팩이 세트째 제외)
 *  · 알레르기·금기  — 오역이 곧 투약 사고
 *  · 격리·감염관리  — 전파 경로 오역
 *  · 수가·급여·본인부담 — 규제(고시) 어휘. 오역은 청구 오류
 *  · 게이트·결정 층 — OFF/WARN/BLOCK·허가권자/위원회/직원 층은 **하위가 상위를 대체하지 못한다**
 *  · 동의·법정 서식 — 법적 효력
 */

export interface SafetyKeyVerdict {
  safety: boolean;
  /** 어느 축에 걸렸는가 — 화면이 배지 툴팁으로 그대로 보여준다. 안전 키가 아니면 null */
  reason: string | null;
}

/** 축 이름 → 패턴. 🔴 여기 추가할 때는 위 주석의 근거도 함께 적는다(근거 없는 패턴은 늘지 않게). */
export const SAFETY_KEY_AXES: ReadonlyArray<{ axis: string; re: RegExp }> = [
  { axis: '위급값·경보', re: /위급|긴급|응급|경보|알람|위험|치명|critical|사망|심정지|코드\s*블루|CPR|소생/i },
  { axis: 'KTAS·중증도', re: /KTAS|중증도|분류\s*등급|소생술|긴급도|triage|트리아지/i },
  { axis: '투약·MAR', re: /투약|복용|용량|용법|처방|약물|약품|MAR|주사|정맥|근주|경구|점적|희석|mg|mL|서방|분할/i },
  { axis: '혈액·수혈', re: /수혈|혈액|적혈구|혈소판|혈장|교차\s*시험|ABO|Rh|혈액형|채혈|헌혈/i },
  { axis: '연하·식이', re: /연하|삼킴|질감|점도|저잔사|유동식|금식|NPO|흡인|사레/i },
  { axis: '알레르기·금기', re: /알레르기|알러지|과민|금기|부작용|이상\s*반응|아나필락시스|상호작용|중복\s*투약|DUR/i },
  { axis: '격리·감염관리', re: /격리|감염|전파|접촉\s*주의|비말|공기\s*주의|멸균|소독|손\s*위생|다제내성/i },
  { axis: '수가·급여·규제', re: /수가|급여|비급여|본인\s*부담|산정\s*특례|감면|청구|심사|고시|보험|의료급여|EDI|삭감/i },
  { axis: '게이트·결정 층', re: /게이트|차단|BLOCK|WARN|승인|반려|결재|의결|위원회|허가|규정|정책|강제|봉쇄/i },
  { axis: '동의·법정 서식', re: /동의서|동의\s*철회|법정|서식|증명서|진단서|소견서|의무\s*기록|개인\s*정보|서명/i },
  { axis: '검체·검사 안전', re: /검체|채취|라벨|바코드|오인|환자\s*확인|본인\s*확인|타임\s*아웃|수술\s*부위|좌우|laterality/i },
  { axis: '낙상·욕창·안전사고', re: /낙상|욕창|억제대|자해|자살|폭력|안전\s*사고|고위험/i },
];

/**
 * 이 카탈로그 키가 안전 키인가.
 *
 * 판정 대상은 **한국어 원문 부분**이다(`원문@문맥` 의 문맥 꼬리는 화면 이름이라 오탐을 만든다 —
 * 예: `이탈@CRM` 의 'CRM' 은 안전 축이 아니다). 문맥은 별도로 본다.
 */
export function classifySafetyKey(key: string): SafetyKeyVerdict {
  const at = key.lastIndexOf('@');
  const source = at > 0 ? key.slice(0, at) : key;
  const hits: string[] = [];
  for (const { axis, re } of SAFETY_KEY_AXES) {
    if (re.test(source)) hits.push(axis);
  }
  if (hits.length === 0) return { safety: false, reason: null };
  return { safety: true, reason: hits.join(' · ') };
}
