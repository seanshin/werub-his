// SSR/최초 클라이언트 렌더는 항상 'ko'로 시작(하이드레이션 불일치 방지).
// 저장된 언어는 마운트 후 useHydrateLocale()에서 적용한다.
export const usePortalLocale = create<{ locale: PortalLocale; setLocale: (l: PortalLocale) => void }>((set) => ({
  locale: 'ko',
  setLocale: (l) => {
    try {
      localStorage.setItem('portal-locale', l);
      document.cookie = `hr_locale=${l}; path=/; max-age=31536000; samesite=lax`; // SSR 자동번역용
    } catch { /* */ }
    set({ locale: l });
  },
}));

/** 마운트 후 저장된 언어 적용(하이드레이션 안전). 클라이언트 진입점(GNB·포털)에서 1회 호출. */
export function useHydrateLocale() {
  const setLocale = usePortalLocale((s) => s.setLocale);
  useEffect(() => {
    try {
      const saved = localStorage.getItem('portal-locale') as PortalLocale | null;
      if (saved && saved !== 'ko' && PORTAL_LANGS.some((l) => l.v === saved)) setLocale(saved);
    } catch { /* */ }
  }, [setLocale]);
}

/** 한국어 원문 → 현재 언어 번역(미등록 시 원문). */
/** 번역 조회 — 미등록이면 한국어 원문 + `missing: true`(조용한 폴백 금지) */
export function trOf(ko: string, locale: PortalLocale): { text: string; missing: boolean } {
  if (locale === 'ko') return { text: ko, missing: false };
  const hit = CATALOG[locale]?.[ko];
  return hit ? { text: hit, missing: false } : { text: ko, missing: true };
}

export function useT() {
  const locale = usePortalLocale((s) => s.locale);
  // 🔴 문자열만 돌려주는 자리 — 누락 여부가 필요하면 `trOf` 를 쓴다(위 헤더 주석 참조)
  return (ko: string): string => trOf(ko, locale).text;
}

/** 현재 언어에서 등재된 키 수 / 전체 조회 대상 — 관제·고지용(분모 병기) */
export function portalCatalogSize(locale: PortalLocale): number {
  return locale === 'ko' ? 0 : Object.keys(CATALOG[locale] ?? {}).length;
}
