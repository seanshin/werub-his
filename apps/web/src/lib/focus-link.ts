/**
 * 원본 화면 링크를 **초점 모드**(사이드바 없는 화면)로 바꾼다.
 *
 * 🔴 왜: 기록 상세 창(`/record-detail/…`)은 "그 기록만 본다"가 목적인 초점 창인데,
 *    하단 '전체 목록·원본 화면에서 보기'가 `(main)` 전체 앱을 열어 **사이드바까지 딸려 나왔다**
 *    (2026-08-25 사람 신고). 초점 창에서 눌렀는데 전체 앱으로 돌아가면 그 창의 목적이 깨진다.
 *    `(main)` 레이아웃은 이미 `?focus=1` 표면을 갖고 있으므로 **새 화면을 만들지 않고 그것을 쓴다.**
 *
 * 🔴 서버가 주는 `link` 는 그대로 둔다 — 목적지를 정하는 것은 서버, 어떻게 열지는 화면이다.
 *    (서버 계약을 바꾸면 이 링크를 쓰는 다른 소비처까지 함께 바뀐다.)
 */
/**
 * 🔴 한 번 껐다가 다시 켰다(2026-08-25) — **끈 판단이 근거 부족이었다.**
 *
 * 신고: 이 링크를 누르면 스피너만 돈다. 그 스피너는 `(main)` 레이아웃의 인증 로딩 분기다.
 * 그래서 처음엔 "내가 미검증 경로로 보내서"라고 보고 껐다. 그런데 코드를 다시 읽으니:
 *
 *   ① 스피너 분기(`if (isLoading) return …`)는 **`focusMode` 분기보다 위에 있다** —
 *      쿼리 파라미터는 그 분기에 아무 영향도 주지 못한다.
 *   ② 초점 분기가 그리는 컴포넌트는 일반 분기의 **부분집합**이다
 *      (사이드바·탑바·AI챗·인증배지·위급값배너가 빠진다). 더 적게 그리는 쪽이 멈출 수 없다.
 *   ③ 비로그인·잘못된 토큰 두 경우 모두 `/login` 으로 정상 리다이렉트된다(실측).
 *
 * → **`focus=1` 은 그 스피너의 원인이 될 수 없다.** 신고 시각(17:20)이 웹 재배포 스왑(17:16) 직후라
 *   그때의 일시적 상태였을 가능성이 높다. 다만 **로그인 상태 재현을 하지 못했으므로 단정하지 않는다.**
 *   또 멈추면 그때는 `focus=1` 이 원인이라는 첫 증거가 되므로, 콘솔 오류와 함께 다시 판정한다.
 *
 * 🔴 교훈: **원인을 모른 채 끄는 것도 "모른다"를 감추는 방식이다.**
 *   구조가 배제하는 가설을 근거로 기능을 접으면, 진짜 원인은 그대로 남는다.
 */
export const FOCUS_LINK_ENABLED = true;

export function toFocusLink(link: string): string {
  // 게이트 — 위 주석 참조. 끄면 링크를 그대로 둔다(사용자를 다른 경로로 보내지 않는다).
  if (!FOCUS_LINK_ENABLED) return link;

  if (!link || typeof link !== 'string') return link;
  // 내부 경로가 아니면 손대지 않는다(외부 링크에 우리 파라미터를 붙이지 않는다)
  if (!link.startsWith('/')) return link;

  const [pathAndQuery, hash] = link.split('#');
  const [path, query = ''] = pathAndQuery.split('?');
  const params = new URLSearchParams(query);
  if (params.get('focus') === '1' && params.get('only') === '1') return link; // 멱등
  params.set('focus', '1');
  // 🔴 `only=1` — 그 기록이 있는 영역만 그린다(환자 헤더·탭 목록·되돌아가기 제외).
  //    기록 한 건을 눌러 들어온 창이라 차트를 훑는 장치는 방해가 된다(2026-08-25 사람 신고).
  //    `focus` 와 **다른 축**이다: focus 는 화면 밖(사이드바), only 는 화면 안(무엇을 그리는가).
  params.set('only', '1');
  return `${path}?${params.toString()}${hash ? `#${hash}` : ''}`;
}
